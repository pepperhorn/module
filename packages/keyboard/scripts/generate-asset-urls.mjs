import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const root = new URL('../', import.meta.url)
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'))
const kit = read('assets/drums/kit.json')
const pianoNotes = read('assets/piano/notes.json')
const files = (dir, names, formats) => names.flatMap(name => formats.map(format => `${dir}/${name}.${format}`))

export const sampleFiles = [
  ...files('piano', pianoNotes, ['ogg', 'm4a']),
  ...files('drums', Object.values(kit.samples).map(({ file }) => file.replace(/\.[^.]+$/, '')), kit.formats),
].sort()

export function assetUrlsModule(relativeAssets) {
  return '// Generated by scripts/generate-asset-urls.mjs.\n' +
    'export const assetUrls = {\n' +
    sampleFiles.map(file => `  ${JSON.stringify(file)}: () => new URL(${JSON.stringify(relativeAssets + file)}, import.meta.url).href,\n`).join('') +
    '}\n'
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  writeFileSync(new URL('src/patches/assetUrls.generated.ts', root), assetUrlsModule('../../assets/'))
}
